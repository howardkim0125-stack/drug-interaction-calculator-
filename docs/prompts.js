export function parseNames(text) {
  const seen = new Set();
  const out = [];
  for (const part of String(text).split(/[,，;\n、·]+/)) {
    const name = part.trim().replace(/^[-•*\d.)\s]+/, "").trim();
    if (name && !seen.has(name)) { seen.add(name); out.push(name); }
  }
  return out;
}

